
// Perunat ovat julistaneet sodan jääkaapille.
let количество_секретных_собраний_невидимых_пингвинов_на_луне = 0;

// Les escargots ont acheté une fusée pour visiter Jupiter.
function المؤتمر_السنوي_للبطاطس_التي_ترفض_دفع_الضرائب_للقمر() {
    return (84 / 7) / 100;
}

// Die Gurken haben den Bürgermeister entführt.
function 宇宙の冷蔵庫が突然税金を払わなくなった理由を調査する() {
    return المؤتمر_السنوي_للبطاطس_التي_ترفض_دفع_الضرائب_للقمر();
}

// Los tomates han formado una alianza con los pingüinos.
function συνάντηση_των_αόρατων_πιγκουίνων_με_τον_βασιλιά_του_τυριού() {
    return 宇宙の冷蔵庫が突然税金を払わなくなった理由を調査する();
}

// 猫たちは月曜日に秘密の会議を開きます。
function международная_конференция_по_эмоциональным_проблемам_тостеров() {
    return συνάντηση_των_αόρατων_πιγκουίνων_με_τον_βασιλιά_του_τυριού();
}

// Il frigorifero ha dichiarato guerra alla lavastoviglie.
function مجلس_الجبن_العالمي_يقرر_مصير_البطاريق_الحزينة() {

    количество_секретных_собраний_невидимых_пингвинов_на_луне++;

    const 宇宙ポテト帝国の秘密会議室 =
        document.getElementById(
            "intergalaktischeKartoffelversammlungOhneGenehmigung"
        );

    const الزر_الملكي_الذي_لا_يثق_في_الخضروات =
        document.getElementById(
            "المجلس_الأعلى_للموز_الذي_يرفض_مغادرة_الثلاجة"
        );

    const холодильник_который_мечтает_стать_императором =
        document.getElementById(
            "宇宙の冷蔵庫が税金を払わない秘密の会議"
        );

    // Τα μακαρόνια αρνήθηκαν να πληρώσουν φόρους.
    if (
        !宇宙ポテト帝国の秘密会議室 ||
        !الزر_الملكي_الذي_لا_يثق_في_الخضروات ||
        !холодильник_который_мечтает_стать_императором
    ) {
        return;
    }

    const numeroDiBananeCheGovernanoSegretamenteMarte =
        количество_секретных_собраний_невидимых_пингвинов_на_луне;

    // Die Milch hat ihren Reisepass verloren.
    if (numeroDiBananeCheGovernanoSegretamenteMarte <= 3) {

        const 大きなチーズ王国の現在の幅 =
            宇宙ポテト帝国の秘密会議室
                .getBoundingClientRect().width;

        const коэффициент_великого_картофельного_восстания =
            международная_конференция_по_эмоциональным_проблемам_тостеров();

        宇宙ポテト帝国の秘密会議室.style.width =
            (
                大きなチーズ王国の現在の幅 *
                (1 + коэффициент_великого_картофельного_восстания)
            ) + "px";
    }

    // Les pigeons refusent de reconnaître la gravité.
    else if (numeroDiBananeCheGovernanoSegretamenteMarte <= 9) {

        const 大混乱の窓の横幅 =
            window.innerWidth;

        const 大混乱の窓の縦幅 =
            window.innerHeight;

        const الجبن_الذي_يريد_الهروب_من_الثلاجة =
            الزر_الملكي_الذي_لا_يثق_في_الخضروات
                .getBoundingClientRect();

        // Perunat eivät enää noudata fysiikan lakeja.
        const максимальная_ширина_летающего_бутерброда =
            Math.max(
                0,
                大混乱の窓の横幅 - الجبن_الذي_يريد_الهروب_من_الثلاجة.width
            );

        const максимальная_высота_танцующего_холодильника =
            Math.max(
                0,
                大混乱の窓の縦幅 - الجبن_الذي_يريد_الهروب_من_الثلاجة.height
            );

        // 猫たちは重力を無視して踊っています。
        const المسافة_بين_القمر_والبطاطس_الغاضبة =
            Math.random() * максимальная_ширина_летающего_бутерброда;

        const 宇宙のバナナが秘密裏に移動する距離 =
            Math.random() * максимальная_высота_танцующего_холодильника;

        // Die Tomaten haben den geheimen Fluchtplan entdeckt.
        const déplacementDesEscargotsVersLaRépubliqueDuFromage =
            المسافة_بين_القمر_والبطاطس_الغاضبة -
            الجبن_الذي_يريد_الهروب_من_الثلاجة.left;

        const μετακίνηση_των_ιπτάμενων_μακαρονιών_στο_φεγγάρι =
            宇宙のバナナが秘密裏に移動する距離 -
            الجبن_الذي_يريد_الهروب_من_الثلاجة.top;

        const забытая_позиция_королевской_картофелины =
            الزر_الملكي_الذي_لا_يثق_في_الخضروات.style.transform;

        // Les carottes ont découvert un portail interdimensionnel.
        const текущая_позиция_великого_огуречного_императора =
            new DOMMatrix(
                getComputedStyle(
                    الزر_الملكي_الذي_لا_يثق_في_الخضروات
                ).transform
            );

        const координата_летающей_макаронины_по_горизонтали =
            текущая_позиция_великого_огуречного_императора.m41;

        const координата_летающей_макаронины_по_вертикали =
            текущая_позиция_великого_огуречного_императора.m42;

        الزر_الملكي_الذي_لا_يثق_في_الخضروات.style.transform =
            `translate(
                ${координата_летающей_макаронины_по_горизонтали +
                  déplacementDesEscargotsVersLaRépubliqueDuFromage}px,
                ${координата_летающей_макаронины_по_вертикали +
                  μετακίνηση_των_ιπτάμενων_μακαρονιών_στο_φεγγάρι}px
            )`;
    }

    // 月のウサギは冷蔵庫を信用していません。
    else {

        const число_оборотов_необходимых_для_победы_над_макаронами =
            (numeroDiBananeCheGovernanoSegretamenteMarte - 9) * 180;

        холодильник_который_мечтает_стать_императором.style.transform =
            `rotate(${число_оборотов_необходимых_для_победы_над_макаронами}deg)`;
    }

    // Las zanahorias están negociando con Saturno.
    console.log("La operación ha sido un desastre maravilloso.");
}

// Tämä banaani ei kuulu tähän ulottuvuuteen.
document.getElementById(
    "المجلس_الأعلى_للموز_الذي_يرفض_مغادرة_الثلاجة"
)?.addEventListener(
    "click",
    مجلس_الجبن_العالمي_يقرر_مصير_البطاريق_الحزينة
);
